#!/usr/bin/env python3
"""Generate an independent register-address fixture from the pinned ADT.

Register interpretation is from BootKC a36b9241 at 0x92cadb0 and 0x92b85dc.
No firmware executes; no secrets or calibration values are extracted.
"""
import argparse, hashlib, json, struct
from pathlib import Path

def parse(raw):
    at=0;nodes={}
    def node(parent,depth):
        nonlocal at
        assert depth<32 and at+8<=len(raw)
        count,children=struct.unpack_from('<II',raw,at);at+=8
        assert count<4096 and children<1024
        props={}
        for _ in range(count):
            key=raw[at:at+32].split(b'\0')[0].decode('ascii')
            size=struct.unpack_from('<I',raw,at+32)[0]&0x7fffffff;at+=36
            assert at+size<=len(raw);props[key]=raw[at:at+size];at+=(size+3)&~3
        name=props['name'].split(b'\0')[0].decode('ascii')
        path='/' if parent is None else parent.rstrip('/')+'/'+name;nodes[path]=props
        for _ in range(children):node(path,depth+1)
    node(None,0);assert at==len(raw);return nodes

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--dtree',type=Path,required=True)
    ap.add_argument('--output-dir',type=Path,required=True);a=ap.parse_args()
    raw=a.dtree.read_bytes();sha=hashlib.sha256(raw).hexdigest()
    assert sha=='0a29c3adc1b8621150445e7082630ac221b76a7a168cbff8a3e1f0d5c72992d0'
    nodes=parse(raw);pmgr=nodes['/arm-io/pmgr']
    groups=[struct.unpack_from('<9I',pmgr['perf-groups'],i) for i in range(0,len(pmgr['perf-groups']),36)]
    offsets=[{0} for g in groups]
    for i in range(0,len(pmgr['perf-counters']),64):
        c=pmgr['perf-counters'][i:i+64]
        if c[0]==3:continue
        pairs=[(c[4],struct.unpack_from('<I',c,8)[0])]
        if c[0]==1 and c[1] in (1,2):pairs.append((c[5],struct.unpack_from('<I',c,12)[0]))
        for group,start in pairs:
            offsets[group].update([start,start+groups[group][3],start+groups[group][3]+4])
    ranges=[struct.unpack_from('<QQQ',nodes['/arm-io']['ranges'],i) for i in range(0,len(nodes['/arm-io']['ranges']),24)]
    rows=[];lines=['/* Pinned independent counter-address fixture: BootKC a36b9241, ADT 0a29c3ad.',
      ' * 0x92cadb0: two data words; 0x92b85dc: secondary for flags 1 or 2.',
      ' * Generated by generate-apple-modern-pmgr-counter-table.py; no calibration. */']
    for i,g in enumerate(groups):
        child,size=struct.unpack_from('<QQ',pmgr['reg'],g[0]*16)
        base=next(pa+child-bus for bus,pa,span in ranges if bus<=child<child+size<=bus+span)+g[1]
        values=sorted(offsets[i]);vals=[hex(v) for v in values]
        rows.append({'group':i,'physical_base':hex(base),'register_count':len(values),'span':hex(max(values)+4),'offsets':vals})
        lines.append(f'static const uint16_t counter_offsets_{i}[] = {{')
        lines.extend('    '+', '.join(vals[k:k+12])+',' for k in range(0,len(vals),12));lines.append('};')
    lines.append('static const struct { const uint16_t *offsets; unsigned count; } counter_expect[8] = {')
    lines.extend(f'    {{counter_offsets_{i}, {len(offsets[i])}}},' for i in range(8));lines.append('};')
    a.output_dir.mkdir(exist_ok=True)
    (a.output_dir/'test-apple-modern-pmgr-counter-table.inc').write_text('\n'.join(lines)+'\n')
    (a.output_dir/'apple-modern-pmgr-counter-table.json').write_text(json.dumps({'dtree_sha256':sha,
      'bootkc_sha256':'a36b924108b63eefd7cc8fa9e54acc3a07544786d3edb316fbcf3b9fb7426b35','groups':rows},indent=2)+'\n')
    print([(g['group'],g['register_count'],g['span']) for g in rows]);print('total registers',sum(map(len,offsets)))
if __name__=='__main__':main()
