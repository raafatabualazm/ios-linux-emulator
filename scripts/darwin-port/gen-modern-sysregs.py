#!/usr/bin/env python3
"""Generate target/arm/modern-sysregs.inc.c from the pinned Darwin-VM tables.

Darwin-VM (qemu-sptm 2867d847, scripts/darwin/{sysregs,dumpregs}.py) models
roughly 200 Apple implementation-defined system registers as read-as-written
storage with a few documented reset values (hw/arm/apple_regs.c). This script
reuses those exact register lists and encodings, but emits Inferno-style
ARMCPRegInfo entries backed by an array in CPUARMState so that reset and VHE
aliasing use ordinary QEMU machinery.

Registers owned by dedicated modern CPU modules are excluded:
  - GXF/GL banks, CURRENTG (modern-gxf), AGTCNT*/ACNT* (modern timers);
  - SPRR_CONFIG/PPERM/UPERM (modern-sprr, with real permission effects);
  - APSTS (modern-apsts, read-only master-key status).

The remaining entries are compatibility stores. They do not implement the
hardware effects of CTRR, CTXR, AMX, performance counters, HID chicken bits or
the other registers listed.

Usage: gen-modern-sysregs.py DARWIN_SCRIPTS_DIR > target/arm/modern-sysregs.inc.c
"""
import ast
import re
import sys
from pathlib import Path

scripts = Path(sys.argv[1])
sys.path.insert(0, str(scripts))
from sysregs import all_regs  # noqa: E402

lists = {}
for node in ast.parse((scripts / 'dumpregs.py').read_text()).body:
    if (isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id in ('rs_opaque', 'rs_banked')):
        lists[node.targets[0].id] = ast.literal_eval(node.value)

# Darwin's main(): HID registers join the opaque list, then EL2 variants of
# EL1/GL1 registers are injected when they exist.
opaque = list(lists['rs_opaque']) + [r for r in all_regs if 'HID' in r]
# Darwin's banked list also stores these per guarded level; no modern module
# owns them, so they become per-level stores here.
for base in lists['rs_banked']:
    if base in ('PMCR1_GL', 'AFSR1_GL'):
        opaque += [f'{base}1', f'{base}2']


def inject_el2(regs):
    for r in list(regs):
        for one, two in (('_EL1', '_EL2'), ('_GL1', '_GL2')):
            alt = r.replace(one, two)
            if one in r and alt not in regs and alt in all_regs:
                regs.append(alt)


inject_el2(opaque)


def decode(name):
    return tuple(int(x) for x in re.sub('[cs]', '', all_regs[name].lower()).split('_'))


EXCLUDE_PREFIX = ('GXF_', 'AGTCNT', 'ACNT', 'CURRENTG', 'SP_GL', 'TPIDR_GL',
                  'VBAR_GL', 'FAR_GL', 'ESR_GL', 'ELR_GL', 'SPSR_GL',
                  'ASPSR_GL', 'SPRR_CONFIG_', 'SPRR_PPERM_', 'SPRR_UPERM_',
                  'APSTS_')
# Exact encodings owned by modern-sprr and modern-apsts, checked independently
# of the names so a renamed table entry cannot re-register them.
OWNED_ENCODINGS = {
    (3, 6, 15, 1, 5),   # SPRR_UPERM_EL0
    (3, 6, 15, 1, 0),   # SPRR_CONFIG_EL1
    (3, 6, 15, 1, 6),   # SPRR_PPERM_EL1
    (3, 6, 15, 14, 2),  # SPRR_CONFIG_EL2
    (3, 6, 15, 1, 7),   # SPRR_PPERM_EL2
    (3, 6, 15, 15, 4),  # SPRR_CONFIG_EL12
    (3, 6, 15, 15, 7),  # SPRR_PPERM_EL12
    (3, 6, 15, 12, 4),  # APSTS_EL1
    (3, 6, 15, 12, 3),  # APSTS_EL2
    (3, 6, 15, 14, 7),  # APSTS_EL12
}
seen, regs = set(), []
for name in opaque:
    if name not in all_regs or name.startswith(EXCLUDE_PREFIX):
        continue
    if '_EL12' in name or '_GL12' in name:
        continue
    enc = decode(name)
    if enc in seen or enc in OWNED_ENCODINGS:
        continue
    seen.add(enc)
    regs.append((name, enc))

# Documented Darwin reset values (apple_regs.c "magic numbers"). APSTS is
# provided by modern-apsts instead of a constant.
RESET = {
    'APCTL_EL1': 0xFF,
    'AMXIDR_EL1': 0x10003,
    'CTRR_A_CTL_EL2': 0x8000000000000001, 'CTRR_B_CTL_EL2': 0x8000000000000001,
    'ACC_CTRR_A_CTL_EL2': 0x8000000000000001,
    'ACC_CTRR_B_CTL_EL2': 0x8000000000000001,
    'ACC_CTRR_C_CTL_EL2': 0x8000000000000001,
    'ACC_CTXR_A_CTL_EL2': 0xC000000000AA019A,
    'ACC_CTXR_B_CTL_EL2': 0xC0000000009A02AA,
    'ACC_CTXR_C_CTL_EL2': 0xC000000000AA026A,
    'ACC_CTXR_D_CTL_EL2': 0xC000000000AA02A9,
}
missing = [n for n in RESET if n not in {r for r, _ in regs}]
if missing:
    sys.exit(f'reset values for absent registers: {missing}')


def access(name):
    m = re.search(r'_(?:EL|GL)(\d)', name)
    return f'PL{m.group(1) if m else 1}_RW'


# VHE pairs: EL1 view, EL2 view and EL12 alias all present in Darwin's table.
aliases = []
names = {n for n, _ in regs}
for name, _ in regs:
    if name.endswith('_EL1') or name.endswith('_GL1'):
        two = name[:-1] + '2'
        twelve = name[:-1] + '12'
        if two in names and twelve in all_regs:
            if decode(twelve) in OWNED_ENCODINGS:
                continue
            aliases.append((name, two, twelve))

print('/* Generated by scripts/darwin-port/gen-modern-sysregs.py from the pinned')
print(' * Darwin-VM register tables. Do not edit by hand. Compatibility stores only. */')
print(f'#define APPLE_MODERN_OPAQUE_COUNT {len(regs)}')
print()
print('static const ARMCPRegInfo apple_modern_sysregs[] = {')
for i, (name, enc) in enumerate(regs):
    reset = RESET.get(name, 0)
    print(f'    {{ .name = "{name}", .state = ARM_CP_STATE_AA64, '
          f'.opc0 = {enc[0]}, .opc1 = {enc[1]}, .crn = {enc[2]}, '
          f'.crm = {enc[3]}, .opc2 = {enc[4]},')
    print(f'      .access = {access(name)}, .resetvalue = 0x{reset:x}ULL,')
    print(f'      .fieldoffset = offsetof(CPUARMState, '
          f'modern_sysregs.opaque[{i}]) }},')
print('};')
print()
print('static const char *const apple_modern_sysreg_names[APPLE_MODERN_OPAQUE_COUNT] = {')
for name, _ in regs:
    print(f'    "{name}",')
print('};')
print()
print('static const struct {')
print('    uint32_t src, dst, alias;')
print('    const char *src_name, *dst_name, *alias_name;')
print('} apple_modern_sysreg_aliases[] = {')
for one, two, twelve in aliases:
    k = [decode(n) for n in (one, two, twelve)]
    keys = ', '.join(f'ENCODE_AA64_CP_REG(CP_REG_ARM64_SYSREG_CP, {e[2]}, {e[3]}, '
                     f'{e[0]}, {e[1]}, {e[4]})' for e in k)
    print(f'    {{ {keys},')
    print(f'      "{one}", "{two}", "{twelve}" }},')
print('};')
