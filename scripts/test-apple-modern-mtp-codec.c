static const uint8_t digitizer_desc[29] = {
    0x05, 0x0d, 0x09, 0x04, 0xa1, 0x01, 0x06, 0x00, 0xff, 0x09, 0x23, 0x95, 0x01, 0xa1, 0x00,
    0x05, 0x0d, 0x09, 0x04, 0x77, 0xff, 0xff, 0x01, 0x00, 0x82, 0x22, 0x01, 0xc0, 0xc0,
};

static uint32_t rd32(const uint8_t *p)
{
    return (uint32_t)p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24;
}

static int rd16s(const uint8_t *p)
{
    return (int16_t)(p[0] | p[1] << 8);
}

int main(void)
{
    /* --- SCMFIFO framing against bytes the guest logged ------------------------------ */
    expect_scm(0x11, 1, 0, "C1 02", 0x80,        /* AP: SET FEATURE C1 02, touch-attach3/7 TX */
               "08 11 0C 00 01 00 00 00 80 00 02 00 00 00 00 00 C1 02 00 00 B5 EB F1 FF");
    expect_scm(0x11, 2, 0, "C1 02", 0x80,        /* same request, transfer id 2 (touch-attach7) */
               "08 11 0C 00 02 00 00 00 80 00 02 00 00 00 00 00 C1 02 00 00 B4 EB F1 FF");
    expect_scm(0x11, 1, 0, "B4 01", 0x80,        /* AP: SET FEATURE B4 01 (touch-attach7 TX) */
               "08 11 0C 00 01 00 00 00 80 00 02 00 00 00 00 00 B4 01 00 00 C2 EC F1 FF");
    expect_scm(0x12, 0, 0, "F1 01 01 00", 0,     /* device: READY interface 1 status 1 (touch-attach7 RX) */
               "08 12 0C 00 00 00 00 00 00 00 04 00 00 00 00 00 F1 01 01 00 06 EC EE FF");
    expect_scm(0x12, 0, 0, "F1 01 00 00", 0,     /* device: READY interface 1 status 0 (SCM-WIRE.md 11) */
               "08 12 0C 00 00 00 00 00 00 00 04 00 00 00 00 00 F1 01 00 00 06 EC EF FF");
    expect_scm(0x11, 1, 0, "", 0x80,             /* device: acknowledgement, empty payload (touch-attach7 RX) */
               "08 11 08 00 01 00 00 00 80 00 00 00 00 00 00 00 76 EE F7 FF");
    expect_scm(0x11, 2, 0, "", 0x80,
               "08 11 08 00 02 00 00 00 80 00 00 00 00 00 00 00 75 EE F7 FF");
    expect_scm(0x11, 4, 0, "41 01 01 00", 0x81, /* GET reply for the power report (touch-attach7 RX) */
               "08 11 0C 00 04 00 00 00 81 00 04 00 00 00 00 00 41 01 01 00 31 ED EE FF");

    /* a payload that needs padding: the 5-byte BF set report of touch-attach7 (TX) */
    {
        uint8_t got[APPLE_MODERN_SCM_MAX_MSG], want[64], pl[5] = { 0xbf, 0x9d, 0x81, 0x09, 0x00 };
        size_t wlen = unhex("08 11 10 00 04 01 00 00 80 00 05 00 00 00 00 00 BF 9D 81 09 00 00 00 00", want);
        size_t glen = apple_modern_scm_encode(got, 0x11, 4, 1, pl, sizeof(pl), true, 0x80, 0);

        /* the AP's own pad bytes are not zero (it checksums its buffer), so compare up to the pad */
        CHECK(glen == wlen + 4);
        CHECK(!memcmp(got, want, 21));
        CHECK(got[2] == 0x10 && got[3] == 0x00);          /* length = round_up(8 + 5, 4) */
        CHECK(!memcmp(got + 21, "\0\0\0", 3));            /* ours are zero */
    }

    /* a non-zero return code travels in sub-header bytes 4..7 (little endian) */
    {
        uint8_t got[APPLE_MODERN_SCM_MAX_MSG];

        CHECK(apple_modern_scm_encode(got, 0x11, 9, 1, NULL, 0, true, 0x81, 0xe00002d6u) == 20);
        CHECK(got[12] == 0xd6 && got[13] == 0x02 && got[14] == 0x00 && got[15] == 0xe0);
        CHECK(got[4] == 9 && got[5] == 1 && got[8] == 0x81);
    }

    /* header without a sub-header: 12 bytes, the type-0 'hello' frame */
    {
        uint8_t got[APPLE_MODERN_SCM_MAX_MSG], want[16];
        size_t wlen = unhex("08 00 00 00 00 00 00 00 F7 FF FF FF", want);

        CHECK(apple_modern_scm_encode(got, 0, 0, 0, NULL, 0, false, 0, 0) == wlen);
        CHECK(!memcmp(got, want, wlen));
    }

    /* --- the interface announcement (SCM-WIRE.md 11, step 1) ------------------------- */
    {
        uint8_t pkt[APPLE_MODERN_MT_INIT_MAX], got[APPLE_MODERN_SCM_MAX_MSG], want[128];
        size_t plen = apple_modern_mt_init_packet(pkt, 1, "multi-touch", digitizer_desc, sizeof(digitizer_desc));
        size_t glen, wlen;

        CHECK(plen == 61);
        glen = apple_modern_scm_encode(got, 0x12, 0, 0, pkt, plen, true, 0, 0);
        wlen = unhex("08 12 48 00 00 00 00 00 00 00 3D 00 00 00 00 00"
                     "F0 01 00 01 6D 75 6C 74 69 2D 74 6F 75 63 68 00 00 00 00 00 00 00"
                     "00 00 1D 00 05 0D 09 04 A1 01 06 00 FF 09 23 95 01 A1 00 05 0D 09 04 77 FF FF 01 00 82 22 01 C0 C0"
                     "04 00 02 00 00 00"
                     "00 00 00 67 0E 3C 30", want);
        CHECK(glen == 84 && wlen == 84);
        CHECK(!memcmp(got, want, 84));
    }

    /* --- the multitouch frame --------------------------------------------------------- */
    for (unsigned i = 0; i < 18; i++) {
        uint8_t want[64], got[APPLE_MODERN_MT_FRAME_LEN];
        size_t wlen = unhex(swipe[i], want);
        const uint8_t *path = want + APPLE_MODERN_MT_HDR_LEN;

        CHECK(wlen == APPLE_MODERN_MT_FRAME_LEN);
        CHECK(apple_modern_mt_frame(got, want[1], rd32(want + 4), path[1], rd16s(path + 4),
                                    rd16s(path + 6), rd16s(path + 8), rd16s(path + 10)) == wlen);
        CHECK(!memcmp(got, want, wlen));
        CHECK(want[1] == i && rd32(want + 4) == 1000 + 16 * i);   /* counter = row, 16 ms cadence */
        if (i > 0 && path[1] == 4) {
            uint8_t prev[64];

            unhex(swipe[i - 1], prev);
            /* the velocity the independent implementation wrote is the one the codec computes */
            CHECK(apple_modern_mt_velocity(rd16s(path + 6) - rd16s(prev + APPLE_MODERN_MT_HDR_LEN + 6),
                                           rd32(want + 4) - rd32(prev + 4)) == rd16s(path + 10));
        }
    }
    CHECK(apple_modern_mt_velocity(296, 16) == 1480);
    CHECK(apple_modern_mt_velocity(297, 16) == 1485);
    CHECK(apple_modern_mt_velocity(-296, 16) == -1480);
    CHECK(apple_modern_mt_velocity(5, 0) == 0);

    /* velocities saturate at the s16 range instead of wrapping */
    {
        uint8_t f[APPLE_MODERN_MT_FRAME_LEN];

        apple_modern_mt_frame(f, 0, 1, 4, 0, 0, 1000000, -1000000);
        CHECK(rd16s(f + 28 + 8) == 32767 && rd16s(f + 28 + 10) == -32768);
        apple_modern_mt_frame(f, 255, 0xfffffffeu, 7, 9999, 7499, 0, 0);
        CHECK(f[1] == 255 && rd32(f + 4) == 0xfffffffeu && rd16s(f + 28 + 4) == 9999 && rd16s(f + 28 + 6) == 7499);
    }

    printf("ok: %u checks\n", checks);
    return 0;
}
